// Builds public/stadium/play/gltf-loader.js — a classic script that adds
// THREE.GLTFLoader to the global three (r150) the stadium app already loads.
//
// three r150 dropped the non-module examples/js builds, and pulling the ES
// module through the app bundler would load a SECOND three instance whose
// classes fail every `instanceof` against the global one. So we take the two
// module sources (they import nothing but "three") and rewrite them into one
// IIFE that destructures the global instead.
//
// Run after bumping the three devDependency:
//   node scripts/stadium/build-gltf-loader.mjs
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "..", "..")
const jsm = path.join(root, "node_modules", "three", "examples", "jsm")
const OUT = path.join(root, "public", "stadium", "play", "gltf-loader.js")

const { version } = JSON.parse(
  readFileSync(path.join(root, "node_modules", "three", "package.json"), "utf8")
)

/** Pull the `import { A, B } from 'three'` names and drop the statement. */
function extractThreeImports(source) {
  const match = source.match(/import\s*\{([\s\S]*?)\}\s*from\s*['"]three['"];?/)
  if (!match) throw new Error("no three import found")
  const names = match[1]
    .split(",")
    .map((name) => name.trim())
    .filter(Boolean)
  return { names, body: source.replace(match[0], "") }
}

function stripLocalImports(source) {
  return source.replace(/^import\s.*?from\s*['"][^'"]+['"];?\s*$/gm, "")
}

function stripExports(source) {
  return source
    .replace(/^export\s*\{[\s\S]*?\};?\s*$/gm, "")
    .replace(/^export\s+(function|const|let|var|class)\s/gm, "$1 ")
}

const utils = extractThreeImports(readFileSync(path.join(jsm, "utils", "BufferGeometryUtils.js"), "utf8"))
const loader = extractThreeImports(readFileSync(path.join(jsm, "loaders", "GLTFLoader.js"), "utf8"))

const names = [...new Set([...utils.names, ...loader.names])].sort()
const bundle = `/* eslint-disable */
// GENERATED by scripts/stadium/build-gltf-loader.mjs from three@${version}
// (examples/jsm GLTFLoader + BufferGeometryUtils). Do not edit by hand.
;(function () {
  "use strict";
  var T = globalThis.THREE;
  if (!T) throw new Error("three must load before gltf-loader.js");
  var { ${names.join(", ")} } = T;

${stripExports(stripLocalImports(utils.body))}

${stripExports(stripLocalImports(loader.body))}

  T.GLTFLoader = GLTFLoader;
})();
`

writeFileSync(OUT, bundle)
console.log(`wrote ${path.relative(root, OUT)} (${(bundle.length / 1024).toFixed(0)}KB, three ${version})`)
