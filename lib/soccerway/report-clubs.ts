/**
 * 경기 리포트 대상 구단 (2026-08-25 운영자 확정) — **순수 모듈**.
 *
 * ## 왜 좁히는가
 * 리포트는 소커웨이 기사를 받아 한국어로 **다시 쓰는** 방식이라, 재료가 얇은 경기일수록
 * 빈칸을 메우려는 힘이 세진다. 실사고: 오사수나 0-0 레반테 경기에 "3-0 승리…멀티골"
 * 리포트가 저장됐다 — 득점 장면 셋이 전부 지어낸 것이었다.
 * 재료가 두껍고 독자가 실제로 찾는 경기만 다루면 그 위험이 근본적으로 줄어든다.
 *
 * ⚠️ 뉴스 관심도 필터(`lib/news/interest-filter.ts`)와 **목록이 다르다.** 거기엔
 *    스트라스부르·라치오·아탈란타가 있지만 여기엔 없다. 운영자가 두 기능에 각각
 *    다른 선을 그었다 — 한쪽을 고칠 때 다른 쪽을 따라 고치지 말 것.
 *
 * ⚠️ **정확일치**로 판정한다(공백·구두점만 접는다). 포함 관계를 쓰면 "레알"이
 *    레알 소시에다드·레알 베티스·레알 오비에도까지 물어온다. 목록에 없는 표기가
 *    들어오면 리포트를 안 만들 뿐이라, 틀리는 쪽이 아니라 **비는 쪽**으로 실패한다.
 */

/** 공백·구두점을 접는다 — betman/LFA 표기 흔들림 흡수 (resolve-team-id 와 같은 규율) */
function norm(s: string): string {
  return String(s ?? "")
    .toLowerCase()
    .replace(/[\s&·．.\-_'"()]/g, "")
    .trim()
}

/** 운영자 지정 구단 — 표기 변형을 모두 적는다 (정확일치라 빠뜨리면 그 표기는 통과 못 한다) */
