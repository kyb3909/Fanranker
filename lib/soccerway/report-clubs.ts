const CLUB_SET = new Set(REPORT_CLUBS.map(norm))

/** 이 팀이 리포트 대상인가 */
export function isReportClub(teamKr: string): boolean {
  const n = norm(teamKr)
  return n.length > 0 && CLUB_SET.has(n)
}

/**
 * 이 경기에 리포트를 쓸 것인가 — **한쪽만 걸려도 쓴다.**
 * 상대가 누구든 대상 구단이 뛴 경기면 독자가 찾는다 (뉴스 필터와 같은 규칙).
 */
export function isReportWorthyMatch(homeKr: string, awayKr: string): boolean {
  return isReportClub(homeKr) || isReportClub(awayKr)
}
