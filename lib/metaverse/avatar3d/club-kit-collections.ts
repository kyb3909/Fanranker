import type {
  ClubKey,
  KitCollarStyle,
  KitItem,
  KitPalette,
  KitPattern,
  KitRarity,
  KitSlot,
} from "./kits"

type ClubKitSeed = {
  slot: KitSlot
  key: string
  name: string
  collection: string
  pattern: KitPattern
  collar?: KitCollarStyle
  palette: KitPalette
  price?: number
  rarity?: KitRarity
}

const palette = (
  primary: string,
  secondary: string,
  dark: string,
  accent: string,
  shorts: string,
  socks: string,
  boots = "#10131A",
  sole = "#E8E5DC"
): KitPalette => ({ primary, secondary, dark, accent, shorts, socks, boots, sole })

function clubKits(clubKey: ClubKey, seeds: readonly ClubKitSeed[]): KitItem[] {
  return seeds.map((seed, index) => ({
    mode: "palette-v1",
    clubKey,
    slot: seed.slot,
    kitKey: seed.key,
    revision: 1,
    name: seed.name,
    collection: seed.collection,
    priceGold: seed.price ?? (index < 2 ? 550 + index * 100 : 750 + (index - 2) * 100),
    rarity: seed.rarity ?? (index < 2 ? "common" : index === 2 ? "rare" : "elite"),
    pattern: seed.pattern,
    collar: seed.collar ?? (["crew", "v", "polo", "crew"] as const)[index % 4],
    palette: seed.palette,
  }))
}

