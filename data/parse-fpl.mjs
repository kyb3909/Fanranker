/**
 * FPL 원본 텍스트 → SQL INSERT 생성기
 * Usage: node data/parse-fpl.mjs > supabase/migrations/038_seed_draft_players.sql
 */
import { readFileSync } from "fs"

const raw = readFileSync("data/fpl-raw.txt", "utf-8")
const lines = raw.split("\n").map((l) => l.trim()).filter(Boolean)

let currentPos = null
const players = []

for (const line of lines) {
  // Position header
  if (["GK", "DEF", "MID", "FW"].includes(line)) {
    currentPos = line
    continue
  }

  // Skip column headers
  if (line.startsWith("Player") && line.includes("Team")) continue

  // Parse: Name\tTeam\tPoints\t£Price
  const parts = line.split("\t")
  if (parts.length < 4) continue

  const name = parts[0].trim()
  const team = parts[1].trim()
  const points = parseInt(parts[2].trim(), 10)
  const priceStr = parts[3].replace("£", "").trim()
  const price = parseFloat(priceStr)

  if (!name || !team || isNaN(points) || isNaN(price) || !currentPos) continue

  players.push({ name, team, position: currentPos, points, price })
}

// Generate SQL
console.log("-- 038: EPL 드래프트 선수 시드 데이터 (FPL 2025-26)")
console.log("-- Auto-generated by data/parse-fpl.mjs")
console.log(`-- Total: ${players.length} players`)
console.log("")
console.log("INSERT INTO draft_players (name, team, position, fpl_price, fpl_points, league) VALUES")

const values = players.map((p, i) => {
  const escaped = p.name.replace(/'/g, "''")
  const teamEsc = p.team.replace(/'/g, "''")
  const comma = i < players.length - 1 ? "," : ";"
  return `  ('${escaped}', '${teamEsc}', '${p.position}', ${p.price}, ${p.points}, 'epl')${comma}`
})

console.log(values.join("\n"))

// Stats
const stats = { GK: 0, DEF: 0, MID: 0, FW: 0 }
players.forEach((p) => stats[p.position]++)
console.error(`\nParsed ${players.length} players: GK=${stats.GK}, DEF=${stats.DEF}, MID=${stats.MID}, FW=${stats.FW}`)
